def load_sections(kb_path: Path) -> dict[str, dict]:
    text = kb_path.read_text(encoding="utf-8")
    parts = re.split(r"(?=^## [^\n]+\n)", text, flags=re.MULTILINE)
    sections = {}
    for part in parts:
        content = part.strip()
        match = re.match(r"^## (.+)", content)
        if not match:
            continue
        section = match.group(1).strip()
        sections[section] = {
            "id": hashlib.md5(content.encode()).hexdigest()[:12],
            "content": content,
            "source": kb_path.name,
            "section": section,
        }
    return sections


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--kb", type=Path, default=Path(__file__).resolve().parent.parent / "data" / "knowledge_base.md")
    args = parser.parse_args()
    sections = load_sections(args.kb)
    assert len(CASES) == 50
    assert len({question for question, _, _ in CASES}) == 50
    assert len(sections) == 8
    output_dir = Path(__file__).resolve().parent
    with (output_dir / "ragas_retrieval_50.jsonl").open("w", encoding="utf-8", newline="\n") as output:
        for question, answer, section_names in CASES:
            docs = [sections[name] for name in section_names]
            sample = {
                "user_input": question,
                "reference": answer,
                "reference_contexts": [doc["content"] for doc in docs],
                "reference_context_ids": [doc["id"] for doc in docs],
            }
            output.write(json.dumps(sample, ensure_ascii=False) + "\n")
    (output_dir / "reference_documents.json").write_text(
        json.dumps({doc["id"]: doc for doc in sections.values()}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
